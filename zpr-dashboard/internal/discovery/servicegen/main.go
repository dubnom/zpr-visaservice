// Command servicegen extracts factual TCP port/name assignments from IANA CSV.
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"io"
	"os"
	"slices"
	"strconv"
	"strings"
)

func main() {
	if err := generate(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(args []string) error {
	if len(args) != 2 {
		return fmt.Errorf("usage: servicegen iana.csv service_registry.go")
	}
	file, err := os.Open(args[0])
	if err != nil {
		return err
	}
	defer file.Close()
	reader := csv.NewReader(file)
	header, err := reader.Read()
	if err != nil {
		return err
	}
	if len(header) < 3 || header[0] != "Service Name" || header[1] != "Port Number" || header[2] != "Transport Protocol" {
		return fmt.Errorf("unexpected IANA CSV columns")
	}
	names := map[int][]string{}
	for {
		row, err := reader.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		port, err := strconv.Atoi(row[1])
		if err != nil || port < 1 || port >= 49152 || row[2] != "tcp" || row[0] == "" {
			continue
		}
		if !slices.Contains(names[port], row[0]) {
			names[port] = append(names[port], row[0])
		}
	}
	if len(names) == 0 {
		return fmt.Errorf("registry contains no named TCP assignments")
	}
	var ports []int
	for port := range names {
		ports = append(ports, port)
	}
	slices.Sort(ports)
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by servicegen from the IANA service-name/port registry; DO NOT EDIT.")
	fmt.Fprintln(&output, "// Source: https://www.iana.org/assignments/service-names-port-numbers/service-names-port-numbers.csv")
	fmt.Fprintln(&output, "// Named TCP assignments only; aliases retain registry order. No descriptions or contacts.")
	fmt.Fprintln(&output, "package discovery")
	fmt.Fprintln(&output, "var ianaTCPServices = map[uint16]string{")
	for _, port := range ports {
		fmt.Fprintf(&output, "%d: %q,\n", port, strings.Join(names[port], ","))
	}
	fmt.Fprintln(&output, "}")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(args[1], formatted, 0644)
}
